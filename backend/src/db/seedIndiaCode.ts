export async function seedIndiaCodeDatabase() {
  try {
    let actCount = 0;
    let secCount = 0;

    for (const item of INDIA_CODE_ACTS) {
      let existingAct = await db.query.acts.findFirst({
        where: eq(acts.title, item.title),
      });

      if (!existingAct) {
        const [newAct] = await db
          .insert(acts)
          .values({
            title: item.title,
            shortTitle: item.shortTitle,
            actNumber: item.actNumber,
            actYear: item.actYear,
            category: item.category,
            ministry: item.ministry,
            indiaCodeUrl: item.indiaCodeUrl,
            overview: item.overview,
          })
          .returning();
        existingAct = newAct;
        actCount++;
      } else {
        // Ensure category and details are up to date
        await db
          .update(acts)
          .set({
            category: item.category,
            shortTitle: item.shortTitle,
            actNumber: item.actNumber,
            actYear: item.actYear,
            ministry: item.ministry,
            indiaCodeUrl: item.indiaCodeUrl,
            overview: item.overview,
          })
          .where(eq(acts.id, existingAct.id));
      }

      for (const s of item.sections) {
        const existingSection = await db.query.actSections.findFirst({
          where: (asTable, { and, eq: eqF }) =>
            and(eqF(asTable.actId, existingAct!.id), eqF(asTable.sectionNumber, s.sectionNumber)),
        });

        if (!existingSection) {
          await db.insert(actSections).values({
            actId: existingAct!.id,
            sectionNumber: s.sectionNumber,
            sectionTitle: s.sectionTitle,
            legalText: s.legalText,
            plainSummary: s.plainSummary,
            punishmentOrRemedy: s.punishmentOrRemedy || 'N/A',
            cognizable: s.cognizable || 'N/A',
            bailable: s.bailable || 'N/A',
            forum: s.forum || 'Competent Court of Law',
            keyPrecedent: s.keyPrecedent,
          });
          secCount++;
        } else {
          // Update section to latest legal text and summaries
          await db
            .update(actSections)
            .set({
              sectionTitle: s.sectionTitle,
              legalText: s.legalText,
              plainSummary: s.plainSummary,
              punishmentOrRemedy: s.punishmentOrRemedy || 'N/A',
              cognizable: s.cognizable || 'N/A',
              bailable: s.bailable || 'N/A',
              forum: s.forum || 'Competent Court of Law',
              keyPrecedent: s.keyPrecedent,
            })
            .where(eq(actSections.id, existingSection.id));
        }
      }
    }

    return { success: true, actCount, secCount, totalActs: INDIA_CODE_ACTS.length };
  } catch (err) {
    console.error('Failed to seed India Code repository:', err);
    throw err;
  }
}
